export type PatternCategory = "chart" | "momentum" | "candlestick";

export interface PatternStage {
  label: string;
  description: string;
}

export interface PatternData {
  slug: string;
  name: string;
  category: PatternCategory;
  tagline: string;
  color: string;
  description: string;
  stages: PatternStage[];
  whatToLookFor: string[];
  howTradersApproach: {
    entry: string;
    invalidation: string;
    target: string;
  };
  whatInvalidates: string[];
  commonMistakes: string[];
  bloomStrategies: string[];
  candles: CandleData[];
  annotations: AnnotationData[];
}

export interface CandleData {
  x: number;
  open: number;
  close: number;
  high: number;
  low: number;
}

export interface AnnotationData {
  x: number;
  y: number;
  label: string;
  anchor?: "start" | "middle" | "end";
}

function bullCandle(x: number, base: number, size: number, wick: number): CandleData {
  return { x, open: base, close: base - size, high: base - size - wick, low: base + wick * 0.5 };
}
function bearCandle(x: number, base: number, size: number, wick: number): CandleData {
  return { x, open: base - size, close: base, high: base - size - wick, low: base + wick * 0.5 };
}

